public static class PkArena
{
    private const uint Arena = 1018;
    private const int MaxActions = 33;
    private const int RoundActions = 3;
    private const int Loops = 3;
    private const int Final = 2;

    private static readonly (uint Item, ushort X, ushort Y)[][] Rounds =
    [
        [(1002020, 71, 29), (1001040, 108, 30), (1002000, 35, 65), (1002010, 32, 69), (1002020, 24, 76), (1001030, 19, 89),
            (1001040, 28, 106), (1002030, 37, 117)],
        [(1002020, 172, 241), (1001040, 179, 204), (1002000, 56, 63), (1002010, 77, 63), (1002020, 71, 29), (1001030, 82, 21),
            (1001040, 95, 11), (1002030, 108, 30)],
        [(1002020, 136, 77), (1001040, 94, 97), (1002000, 101, 47), (1002010, 154, 236), (1002020, 172, 241), (1001030, 168, 228),
            (1001040, 185, 227), (1002030, 197, 210)],
        [(1002020, 70, 133), (1001040, 118, 117), (1002000, 179, 204), (1002010, 167, 193), (1002020, 99, 82), (1001030, 136, 77),
            (1001040, 121, 80), (1002030, 104, 84)],
        [(1002020, 175, 118), (1001040, 139, 139), (1002000, 94, 97), (1002010, 88, 114), (1002020, 76, 121), (1001030, 70, 133),
