            (1001030, 172, 134), (1001040, 188, 142), (1002030, 207, 142)]
    ];

    [Minute(2030003)]
    public static void RainPotions(World world)
    {
        if (world.Random.Next(8) >= Loops)
        {
            world.DropItem(1002000, Arena, 35, 65);
            return;
        }

        for (var actions = 1; actions + RoundActions <= MaxActions; actions += RoundActions)
        {
            var round = Rounds[world.Random.Next(Rounds.Length)];
            var pick = world.Random.Next(round.Length);
            var (item, x, y) = round[pick];

            if (!world.DropItem(item, Arena, x, y) || pick < Final)
            {
                return;
            }
        }
    }
}
